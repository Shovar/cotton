#!/usr/bin/env bash
# Install Cotton for the current user and expose `cotton` on PATH.
#
#   scripts/install.sh
#   scripts/install.sh dist/cotton-0.1.0-py3-none-any.whl
#   scripts/install.sh --prefix ~/.local/share/cotton --bin-dir ~/.local/bin
set -euo pipefail

usage() {
  cat <<'EOF'
Usage: scripts/install.sh [options] [WHEEL]

Without WHEEL, installs this checkout. The frontend is built when the compiled
bundle is missing or older than its sources.

Options:
  --prefix DIR   installation prefix (default: ~/.local/share/cotton)
  --bin-dir DIR  directory for the cotton command (default: ~/.local/bin)
  -h, --help     show this help

The command is a small wrapper that sources ROS_SETUP when set, or the system
ROS 2 setup script when ROS 2 is not active. Re-run the installer to upgrade.
EOF
}

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
prefix="${XDG_DATA_HOME:-$HOME/.local/share}/cotton"
bin_dir="$HOME/.local/bin"
wheel=""

while (($#)); do
  case "$1" in
    -h|--help)
      usage
      exit 0
      ;;
    --prefix)
      [[ $# -ge 2 ]] || { echo "install: --prefix needs a directory" >&2; exit 2; }
      prefix="$2"
      shift 2
      ;;
    --bin-dir)
      [[ $# -ge 2 ]] || { echo "install: --bin-dir needs a directory" >&2; exit 2; }
      bin_dir="$2"
      shift 2
      ;;
    -*)
      echo "install: unknown option: $1" >&2
      usage >&2
      exit 2
      ;;
    *)
      [[ -z "$wheel" ]] || { echo "install: pass only one wheel" >&2; exit 2; }
      wheel="$1"
      shift
      ;;
  esac
done

if [[ -n "${PYTHON:-}" ]]; then
  candidates=("$PYTHON")
else
  candidates=(python3.13 python3.12 python3.11 python3.10 python3)
fi
python=""
for candidate in "${candidates[@]}"; do
  if command -v "$candidate" >/dev/null 2>&1 &&
    "$candidate" -c 'import sys; raise SystemExit(0 if sys.version_info >= (3, 10) else 1)' 2>/dev/null; then
    python="$candidate"
    break
  fi
done
if [[ -z "$python" ]]; then
  echo "install: Python 3.10+ not found; install it or set PYTHON." >&2
  exit 2
fi

if [[ -n "$wheel" ]]; then
  [[ -f "$wheel" ]] || { echo "install: wheel not found: $wheel" >&2; exit 2; }
  wheel="$(cd "$(dirname "$wheel")" && pwd)/$(basename "$wheel")"
  install_target="$wheel"
else
  install_target="$repo_root"
  spa="$repo_root/backend/src/cotton/web"
  frontend_sources=(
    "$repo_root/frontend/src"
    "$repo_root/frontend/index.html"
    "$repo_root/frontend/package.json"
    "$repo_root/frontend/package-lock.json"
    "$repo_root/frontend/tsconfig.json"
    "$repo_root/frontend/vite.config.ts"
  )
  rebuild=false
  if [[ ! -f "$spa/index.html" ]]; then
    rebuild=true
  elif [[ -n "$(find "${frontend_sources[@]}" -newer "$spa/index.html" -print -quit)" ]]; then
    rebuild=true
  fi
  if [[ "$rebuild" == true ]]; then
    command -v npm >/dev/null 2>&1 || {
      echo "install: the frontend is not built and npm is missing." >&2
      echo "install: build a wheel elsewhere or install Node 24+ and retry." >&2
      exit 2
    }
    echo "install: building frontend"
    if ! (cd "$repo_root/frontend" && npm ci && npm run build); then
      echo "install: frontend build failed; fix it or pass a prebuilt wheel." >&2
      exit 1
    fi
    rm -rf "$spa"
    cp -R "$repo_root/frontend/dist" "$spa"
  fi
fi

mkdir -p "$prefix" "$bin_dir"
prefix="$(cd "$prefix" && pwd)"
bin_dir="$(cd "$bin_dir" && pwd)"
venv="$prefix/venv"

if [[ ! -x "$venv/bin/python" ]]; then
  echo "install: creating $venv"
  "$python" -m venv --system-site-packages "$venv"
fi

echo "install: installing $install_target"
"$venv/bin/python" -m pip install --upgrade "$install_target"

bin_src="$prefix/bin/cotton"
mkdir -p "$prefix/bin"
cat > "$bin_src" <<'EOF'
#!/usr/bin/env bash
# Generated by scripts/install.sh. Re-run the installer to update it.
set -euo pipefail

target="$(readlink "${BASH_SOURCE[0]}" 2>/dev/null || true)"
script="${target:-${BASH_SOURCE[0]}}"
prefix="$(cd "$(dirname "$script")/.." && pwd)"
venv="$prefix/venv"

if [[ ! -x "$venv/bin/cotton" ]]; then
  echo "cotton: broken installation at $prefix; re-run the installer." >&2
  exit 2
fi

# Source ROS_SETUP explicitly, or a system ROS 2 when a fresh terminal has
# none. ROS_SETUP also works over an already-sourced /opt/ros environment.
setup="${ROS_SETUP:-}"
if [[ -n "$setup" ]]; then
  if [[ ! -f "$setup" ]]; then
    echo "cotton: ROS_SETUP does not exist: $setup" >&2
    exit 2
  fi
elif ! command -v ros2 >/dev/null 2>&1; then
  if [[ -n "${ROS_DISTRO:-}" && -f "/opt/ros/${ROS_DISTRO}/setup.bash" ]]; then
    setup="/opt/ros/${ROS_DISTRO}/setup.bash"
  else
    shopt -s nullglob
    candidates=(/opt/ros/*/setup.bash)
    shopt -u nullglob
    if (( ${#candidates[@]} == 1 )); then
      setup="${candidates[0]}"
    fi
  fi
fi
if [[ -n "$setup" ]]; then
  set +u
  # shellcheck disable=SC1090
  source "$setup"
  set -u
fi

# Some setup scripts prepend their own site-packages to PYTHONPATH and shadow
# the venv's packages. Keep the venv first, as scripts/dev.sh does.
venv_site="$("$venv/bin/python" -c 'import sysconfig; print(sysconfig.get_paths()["purelib"])')"
export PYTHONPATH="${venv_site}${PYTHONPATH:+:${PYTHONPATH}}"

exec "$venv/bin/cotton" "$@"
EOF
chmod +x "$bin_src"

link="$bin_dir/cotton"
if [[ -e "$link" || -L "$link" ]]; then
  existing="$(readlink "$link" 2>/dev/null || true)"
  if [[ "$existing" != "$bin_src" ]]; then
    echo "install: $link already exists and is not managed by this prefix." >&2
    echo "install: remove it before installing, or choose another --bin-dir." >&2
    exit 2
  fi
fi
if [[ "$link" != "$bin_src" ]]; then
  ln -sfn "$bin_src" "$link"
fi

version="$("$venv/bin/python" -c 'import cotton; print(cotton.__version__)' 2>/dev/null || echo unknown)"
echo "install: Cotton $version installed"
echo "install: command: $link"
case ":$PATH:" in
  *":$bin_dir:"*) ;;
  *) echo "install: add $bin_dir to PATH to call cotton from any terminal." ;;
esac
echo "install: run: cotton"
